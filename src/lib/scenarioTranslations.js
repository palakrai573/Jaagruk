export function translateScenario(scenario, lang) {
  if (lang === 'en') return scenario
  const tr = SCENARIO_TRANSLATIONS[scenario.id]?.[lang]
  if (!tr) return scenario
  return {
    ...scenario,
    title: tr.title || scenario.title,
    intro: tr.intro || scenario.intro,
    steps: scenario.steps.map((step, i) => {
      const trStep = tr.steps?.[i]
      if (!trStep) return step
      return {
        ...step,
        prompt: trStep.prompt || step.prompt,
        choices: step.choices.map((choice, j) => {
          const trChoice = trStep.choices?.[j]
          if (!trChoice) return choice
          return { ...choice, text: trChoice.text || choice.text, feedback: trChoice.feedback || choice.feedback }
        }),
      }
    }),
  }
}
